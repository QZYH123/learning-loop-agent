/**
 * Render a Lucide SVG icon string
 * @param {string} name - The icon name
 * @param {object|number} options - Options object or number size
 * @returns {string} SVG HTML string
 */
export function icon(name, options = {}) {
  const size = typeof options === 'number' ? options : (options.size || 18);
  const className = typeof options === 'object' && options.className ? options.className : '';
  const strokeWidth = typeof options === 'object' && options.strokeWidth ? options.strokeWidth : 2;
  const ariaHidden = typeof options === 'object' && options.ariaHidden !== undefined ? options.ariaHidden : true;

  const content = LUCIDE_ICONS[name] || LUCIDE_ICONS.sparkles;
  const hiddenAttr = ariaHidden ? 'aria-hidden="true"' : '';
  const classAttr = className ? `class="lucide-icon ${className}"` : 'class="lucide-icon"';

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" ${classAttr} ${hiddenAttr}>${content}</svg>`;
}

/**
 * Exported icons helper proxy object allowing `icons.<name>(size, className)`
 */
export const icons = new Proxy({}, {
  get(target, prop) {
    return (size = 18, className = '', strokeWidth = 2) => {
      return icon(prop, { size, className, strokeWidth });
    };
  }
});
